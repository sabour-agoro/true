const dictionaries = { fr, en };

type I18nValue = {
  locale: Locale;
  t: typeof fr;
  setLocale: (locale: Locale) => void;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const locale = useUi((state) => state.locale);
  const setLocale = useUi((state) => state.setLocale);
  const [ready, setReady] = useState(false);

  useEffect(() => {
    const saved = localStorage.getItem("true-locale");
    if (saved === "en" || saved === "fr") setLocale(saved);
    setReady(true);
  }, [setLocale]);

  const value = useMemo<I18nValue>(
    () => ({
      locale: ready ? locale : "fr",
      t: dictionaries[ready ? locale : "fr"],
      setLocale,
    }),
    [locale, ready, setLocale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used within I18nProvider");
  return value;
}
